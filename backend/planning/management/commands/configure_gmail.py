"""Run interactively on the server; credentials never enter shell arguments."""
import getpass
import os
import smtplib
import ssl
import warnings
from pathlib import Path

from django.conf import settings
from django.core.exceptions import ValidationError
from django.core.management.base import BaseCommand, CommandError
from django.core.validators import validate_email
from dotenv import set_key


class Command(BaseCommand):
    help = "Verify Gmail SMTP login and privately save email settings in backend/.env."

    def add_arguments(self, parser):
        parser.add_argument("--email", required=True)

    def handle(self, *args, **options):
        email = options["email"].strip().lower()
        try:
            validate_email(email)
        except ValidationError:
            raise CommandError("Enter a valid Gmail address.") from None
        if not email.endswith("@gmail.com"):
            raise CommandError("This command is for a personal @gmail.com sender.")
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("error", getpass.GetPassWarning)
                password = getpass.getpass("Google App Password (hidden; not your normal Gmail password): ").replace(" ", "")
        except (getpass.GetPassWarning, EOFError):
            raise CommandError("Use an interactive SSH terminal with hidden password entry.") from None
        if len(password) != 16 or not password.isascii() or not password.isalpha():
            raise CommandError("Use the 16-letter App Password generated by Google.")
        try:
            with smtplib.SMTP("smtp.gmail.com", 587, timeout=15) as smtp:
                smtp.ehlo()
                smtp.starttls(context=ssl.create_default_context())
                smtp.ehlo()
                smtp.login(email, password)
        except (smtplib.SMTPException, OSError):
            raise CommandError("Gmail connection failed. Check the App Password, 2-Step Verification and outbound port 587. No settings were changed.") from None
        path = Path(settings.BASE_DIR) / ".env"
        if not path.exists():
            descriptor = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            os.close(descriptor)
        os.chmod(path, 0o600)
        for key, value in {
            "EMAIL_HOST": "smtp.gmail.com", "EMAIL_PORT": "587",
            "EMAIL_HOST_USER": email, "EMAIL_HOST_PASSWORD": password,
            "EMAIL_USE_TLS": "true", "EMAIL_USE_SSL": "false",
            "DEFAULT_FROM_EMAIL": f"Hibi <{email}>",
        }.items():
            set_key(str(path), key, value)
        self.stdout.write(self.style.SUCCESS("Gmail login verified. Email settings saved privately. Restart Django; no secret values were displayed."))
